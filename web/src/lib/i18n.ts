const catalogs: Record<Lang, Catalog> = { en, de, fr, es };
export const lang = writable<Lang>('en');

export function setLang(value: Lang): void {
  lang.set(value);
  if (typeof localStorage !== 'undefined') localStorage.setItem('fs-lang', value);
  if (typeof document !== 'undefined') document.documentElement.lang = value;
}

export function initialLang(): Lang {
  if (typeof localStorage === 'undefined') return 'en';
  const stored = localStorage.getItem('fs-lang');
  return stored === 'de' || stored === 'fr' || stored === 'es' ? stored : 'en';
}

export const t = derived(lang, ($lang) => {
  const catalog = catalogs[$lang];
  return (key: string, vars?: Record<string, string | number>): string => {
    let text = catalog[key] ?? key;
    for (const [name, value] of Object.entries(vars ?? {})) {
      text = text.replace(`{${name}}`, String(value));
    }
    return text;
  };
});
